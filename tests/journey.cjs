const assert = require('node:assert/strict');
const { mkdir } = require('node:fs/promises');
const decodeQr = require('jsqr');
const { chromium } = require('playwright');

async function journey(browser, viewport, capture) {
  const videoDir = capture && process.env.RXEASE_VIDEO;
  const page = await browser.newPage({ viewport, recordVideo: videoDir ? { dir: videoDir, size: viewport } : undefined });
  page.setDefaultTimeout(7000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const click = name => page.getByRole('button', { name, exact: true }).click();
  const fill = (name, value) => page.getByLabel(name, { exact: true }).fill(value);
  const check = name => page.getByLabel(name, { exact: true }).check();
  const has = (text, root = '#panel') => page.locator(root).filter({ hasText: new RegExp(text) }).waitFor();
  const enabled = name => page.getByRole('button', { name, exact: true }).isEnabled();
  const role = name => page.getByLabel('Demo workspace').selectOption(name);
  async function shot(name, target) {
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Horizontal overflow at ' + name);
    if (capture) {
      if (target) await page.getByRole('heading', { name: target, exact: true }).evaluate(node => node.scrollIntoView({ block: 'start' }));
      else await page.evaluate(() => scrollTo(0, 0));
      await page.screenshot({ path: capture + '/' + name + '.png' });
      if (videoDir) await page.waitForTimeout(3200);
    }
  }
  async function qr(label) {
    const image = page.getByRole('img', { name: label });
    const pixels = await image.evaluate(canvas => {
      const scaled = document.createElement('canvas');
      scaled.width = scaled.height = canvas.width * 5;
      const context = scaled.getContext('2d');
      context.imageSmoothingEnabled = false;
      context.drawImage(canvas, 0, 0, scaled.width, scaled.height);
      return { size: scaled.width, data: Array.from(context.getImageData(0, 0, scaled.width, scaled.height).data) };
    });
    const decoded = decodeQr(Uint8ClampedArray.from(pixels.data), pixels.size, pixels.size);
    const token = await image.locator('xpath=following-sibling::code').innerText();
    assert.equal(decoded?.data, token);
    return token;
  }
  const upload = async (name, contents) => page.getByLabel('Synthetic text report').setInputFiles({
    name, mimeType: 'text/plain', buffer: Buffer.from(contents)
  });
  await page.goto(process.env.RXEASE_URL || 'http://localhost:3000');
  await shot('01-start');
  await click('Register demo patient');
  await click('Verify demo contact');
  await has('Use the displayed simulation code');
  await fill('Demo verification code', '0426');
  await click('Verify demo contact');
  await role('Doctor');
  await has('Administrator approval');
  await role('Administrator');
  for (const name of ['Doctor', 'Pharmacist', 'Lab staff']) await click('Approve ' + name);
  await shot('02-administrator');
  await role('Doctor');
  await has('Waiting for patient registration, verification and consent');
  await role('Patient');
  await click('Grant demo care consent');
  const checkIn = await qr('Patient check-in QR');
  await shot('03-check-in');
  await role('Doctor');
  await fill('Patient check-in token', 'wrong');
  await click('Verify and check in');
  await has('Token does not match');
  await fill('Patient check-in token', checkIn);
  await click('Verify and check in');
  await check('I consent to saving this synthetic text');
  assert.equal(await enabled('Approve structured note'), false);
  await click('Focus dictation field');
  assert.ok(await page.getByLabel('Consultation transcript').evaluate(el => el === document.activeElement));
  await click('Load simulated dictation');
  await fill('Presenting concern', 'Fictional screening follow-up');
  await fill('Assessment and next steps', 'Review the report after release');
  assert.equal(await enabled('Approve structured note'), false);
  await check('I reviewed the text, quantities and dates');
  await shot('04-consultation', 'Consultation');
  await click('Approve structured note');
  await check('Simulate a conflicting sensitivity');
  await check('I approve this fictional prescription and calculated quantity');
  assert.equal(await enabled('Issue demo prescription'), false);
  await has('Simulated safety alert');
  await page.getByLabel('Simulate a conflicting sensitivity').uncheck();
  await fill('Days', '0');
  await check('I approve this fictional prescription and calculated quantity');
  assert.equal(await enabled('Issue demo prescription'), false);
  await fill('Days', '6');
  await check('I approve this fictional prescription and calculated quantity');
  await click('Issue demo prescription');
  await click('Order synthetic screening');
  await role('Lab staff');
  await has('Patient sharing consent is required');
  await role('Patient');
  const prescription = await qr('Demo prescription QR');
  await shot('05-prescription', 'Demo prescription');
  await click('Grant lab sharing consent');
  await role('Pharmacist');
  await fill('Prescription token', 'wrong');
  await click('Verify prescription token');
  await has('Unknown prescription token');
  await fill('Prescription token', prescription);
  await click('Verify prescription token');
  for (const invalid of ['13', '0', '1.5']) {
    await fill('Quantity supplied', invalid);
    await click('Record partial or full fill');
    await has('Enter a whole number from 1 to 12');
  }
  await fill('Quantity supplied', '4');
  await click('Record partial or full fill');
  await has('12 prescribed · 4 supplied · 8 outstanding');
  await shot('06-pharmacy');
  await role('Lab staff');
  await upload('sample.txt', 'Synthetic report version one');
  await click('Upload synthetic report');
  await has('confirm its origin');
  await check('This report contains synthetic data only');
  await click('Upload synthetic report');
  await has('Version 1');
  await shot('07-lab');
  await role('Patient');
  await has('awaiting clinician release');
  assert.ok(!(await page.locator('#panel').innerText()).includes('Synthetic report version one'));
  await role('Doctor');
  await click('Approve report version 1');
  await role('Patient');
  assert.ok(!(await page.locator('#panel').innerText()).includes('Synthetic report version one'));
  await role('Doctor');
  await click('Release report version 1');
  await role('Lab staff');
  await upload('corrected.txt', 'Corrected fictional result');
  await check('This report contains synthetic data only');
  await click('Submit corrected report');
  await has('provide a reason');
  await fill('Reason for correction', 'Fixed a fictional accession field');
  await click('Submit corrected report');
  await has('Version 2');
  await role('Patient');
  await has('Released version 1');
  assert.ok(!(await page.locator('#panel').innerText()).includes('Corrected fictional result'));
  await role('Doctor');
  await has('Fixed a fictional accession field');
  await click('Approve report version 2');
  await click('Release report version 2');
  await shot('08-correction', 'Lab orders and release');
  await role('Patient');
  await has('Released version 2');
  await check('I consent to saving this synthetic text');
  await fill('Follow-up transcript', 'I collected 4 or 14 tablets');
  await check('I reviewed the text, quantities and dates');
  assert.equal(await enabled('Send follow-up'), false);
  await has('Resolve the ambiguous quantity');
  await click('Load simulated dictation');
  assert.equal(await enabled('Send follow-up'), false);
  await check('I reviewed the text, quantities and dates');
  await page.getByLabel('I consent to saving this synthetic text').uncheck();
  assert.equal(await enabled('Send follow-up'), false);
  await check('I consent to saving this synthetic text');
  await shot('09-follow-up', 'Voice follow-up');
  await click('Send follow-up');
  await role('Doctor');
  await has('New update');
  await fill('Care plan', 'Review the fictional report at follow-up');
  await fill('Treatment goal', 'Confirm a follow-up date this week');
  await fill('Referral (optional)', 'Demo screening clinic');
  await click('Send care plan');
  await shot('10-plan', 'Follow-up inbox');
  await role('Patient');
  await click('Acknowledge care plan');
  await check('I consent to saving this synthetic text');
  await fill('Follow-up transcript', 'Which fictional clinic should I visit?');
  await check('I reviewed the text, quantities and dates');
  await click('Send clarification');
  const date = new Date();
  date.setDate(date.getDate() + 2);
  await fill('Follow-up date', date.toISOString().slice(0, 10));
  await click('Book follow-up');
  date.setDate(date.getDate() + 1);
  const rescheduled = date.toISOString().slice(0, 10);
  await fill('Follow-up date', rescheduled);
  await click('Reschedule follow-up');
  await role('Doctor');
  await has('New clarification');
  await click('Record attendance for ' + rescheduled);
  await role('Patient');
  await click('Share appointment and goal with caregiver');
  await click('Open caregiver view');
  await has('Attended');
  await has('Confirm a follow-up date this week');
  assert.ok(!await page.getByLabel('Demo workspace').isVisible());
  assert.ok(!await page.getByRole('heading', { name: 'Care timeline' }).isVisible());
  assert.ok(!(await page.locator('#panel').innerText()).includes('Corrected fictional result'));
  await shot('11-caregiver');
  await click('Return to patient workspace');
  await click('Revoke caregiver access');
  assert.equal(await page.getByRole('button', { name: 'Open caregiver view' }).count(), 0);
  await page.reload();
  await has('8 outstanding');
  await has('Released version 2');
  await has('Patient sent a clarification', '#timeline');
  await shot('12-timeline');
  assert.deepEqual(errors, []);
  await page.close();
  console.log('Passed full five-role journey at ' + viewport.width + '×' + viewport.height);
}

(async () => {
  const capture = process.env.RXEASE_CAPTURE;
  if (capture) await mkdir(capture, { recursive: true });
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  try {
    await journey(browser, { width: 1280, height: 800 }, capture);
    await journey(browser, { width: 390, height: 844 });
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
